"""Generates the material preview shapes (OBJ, one material slot each).

Run from this folder:  python generate_preview_meshes.py

All shapes are about 2 scene units across and sit centred on the origin, so the
preview's auto-fit camera and floor handle them like the material tester. They carry
smooth normals and a planar UV per face, which is what the material graphs expect.
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def write_obj(name, positions, uvs, normals, faces):
    with open(os.path.join(HERE, name), 'w', newline='\n') as out:
        out.write('# generated by generate_preview_meshes.py\n')
        for p in positions:
            out.write('v %.6f %.6f %.6f\n' % p)
        for t in uvs:
            out.write('vt %.6f %.6f\n' % t)
        for n in normals:
            out.write('vn %.6f %.6f %.6f\n' % n)
        for f in faces:
            out.write('f ' + ' '.join('%d/%d/%d' % (i + 1, i + 1, i + 1) for i in f) + '\n')


def normalize(v):
    l = math.sqrt(sum(c * c for c in v)) or 1.0
    return tuple(c / l for c in v)


def sphere(radius=1.0, rings=48, segments=96):
    positions, uvs, normals, faces = [], [], [], []
    for r in range(rings + 1):
        v = r / rings
        theta = v * math.pi
        for s in range(segments + 1):
            u = s / segments
            phi = u * 2 * math.pi
            n = (math.sin(theta) * math.cos(phi), math.cos(theta), math.sin(theta) * math.sin(phi))
            positions.append(tuple(c * radius for c in n))
            normals.append(n)
            uvs.append((u, 1 - v))
    stride = segments + 1
    for r in range(rings):
        for s in range(segments):
            a = r * stride + s
            b = a + stride
            faces.append((a, a + 1, b))
            faces.append((a + 1, b + 1, b))
    return positions, uvs, normals, faces


def axis_samples(half, radius, inner=14, rim=10):
    """Sample positions across one face axis: even inside, dense across the rounded rim."""
    inner_half = half - radius
    pts = [(-inner_half + 2 * inner_half * i / inner) for i in range(inner + 1)]
    lo = [-half + radius * i / rim for i in range(rim)]
    hi = [inner_half + radius * (i + 1) / rim for i in range(rim)]
    return sorted(set(round(p, 9) for p in lo + pts + hi))


def rounded_box(half, radius):
    """A box of half extents `half` (x, y, z) with its edges and corners rounded."""
    positions, uvs, normals, faces = [], [], [], []
    inner = tuple(h - radius for h in half)

    def clamp(v, lo, hi):
        return max(lo, min(hi, v))

    # (face axis, sign, the two in-plane axes)
    for axis, sign, (a1, a2) in [(0, 1, (1, 2)), (0, -1, (2, 1)), (1, 1, (2, 0)), (1, -1, (0, 2)), (2, 1, (0, 1)), (2, -1, (1, 0))]:
        s1 = axis_samples(half[a1], radius)
        s2 = axis_samples(half[a2], radius)
        base = len(positions)

        for v in s2:
            for u in s1:
                q = [0.0, 0.0, 0.0]
                q[axis] = sign * half[axis]
                q[a1] = u
                q[a2] = v
                c = tuple(clamp(q[i], -inner[i], inner[i]) for i in range(3))
                d = tuple(q[i] - c[i] for i in range(3))
                n = normalize(d)
                positions.append(tuple(c[i] + n[i] * radius for i in range(3)))
                normals.append(n)
                uvs.append((0.5 + u / (2 * half[a1]), 0.5 + v / (2 * half[a2])))

        w = len(s1)
        for j in range(len(s2) - 1):
            for i in range(w - 1):
                a = base + j * w + i
                b = a + w
                # Keep every face counter-clockwise seen from outside.
                tri = [(a, a + 1, b), (a + 1, b + 1, b)]
                if sign * (1 if (axis, a1, a2) in ((0, 1, 2), (1, 2, 0), (2, 0, 1)) else -1) < 0:
                    tri = [(t[0], t[2], t[1]) for t in tri]
                faces.extend(tri)
    return positions, uvs, normals, faces


def cloth(width=2.2, depth=2.2, folds=3.0, amplitude=0.22, n=120):
    """A draped sheet with soft folds: for sheen and anisotropy, which need curvature and a visible weave direction."""
    positions, uvs, normals, faces = [], [], [], []

    def height(x, z):
        u = x / width * 2 * math.pi * folds
        # folds along x, a gentle sag towards the middle, tapering to the edges
        edge = math.cos(x / width * math.pi) * math.cos(z / depth * math.pi)
        return amplitude * math.sin(u) * max(edge, 0) ** 0.5 + 0.35 * edge * edge

    for j in range(n + 1):
        for i in range(n + 1):
            x = (i / n - 0.5) * width
            z = (j / n - 0.5) * depth
            y = height(x, z)
            e = 1e-3
            dx = (height(x + e, z) - height(x - e, z)) / (2 * e)
            dz = (height(x, z + e) - height(x, z - e)) / (2 * e)
            positions.append((x, y, z))
            normals.append(normalize((-dx, 1.0, -dz)))
            uvs.append((i / n, j / n))
    stride = n + 1
    for j in range(n):
        for i in range(n):
            a = j * stride + i
            b = a + stride
            faces.append((a, b, a + 1))
            faces.append((a + 1, b, b + 1))
    return positions, uvs, normals, faces


if __name__ == '__main__':
    write_obj('preview_sphere.obj', *sphere())
    write_obj('preview_rounded_cube.obj', *rounded_box((0.9, 0.9, 0.9), 0.22))
    write_obj('preview_slab.obj', *rounded_box((1.1, 0.22, 1.1), 0.08))
    write_obj('preview_cloth.obj', *cloth())
    print('ok')
