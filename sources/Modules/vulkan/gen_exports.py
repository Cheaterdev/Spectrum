"""Regenerates vulkan_exports.inc, the names `import vulkan;` cannot carry on its own:
macros (a module cannot export them) and the `static const` 64-bit flag values (internal linkage,
not visible through the header unit). Run after a Vulkan header update:

    python gen_exports.py <vulkan include dir>     (default: ../../../vcpkg_installed/x64-windows/include/vulkan)
"""
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
inc = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "..", "..", "vcpkg_installed", "x64-windows", "include", "vulkan")

core = open(os.path.join(inc, "vulkan_core.h"), encoding="utf-8").read()
win32 = open(os.path.join(inc, "vulkan_win32.h"), encoding="utf-8").read()

out = ["// Generated by gen_exports.py — do not edit.", ""]

for m in re.finditer(r"^static const (Vk\w+) (VK_\w+) = ([^;]+);", core, re.M):
    out.append(f"export inline constexpr {m.group(1)} {m.group(2)} = {m.group(3)};")
out.append("")

for text in (core, win32):
    for m in re.finditer(r'^#define (VK_\w+_EXTENSION_NAME)\s+("[^"]*")', text, re.M):
        out.append(f"export inline constexpr const char* {m.group(1)} = {m.group(2)};")
out.append("")

# Plain numeric macros. VK_NULL_HANDLE, VK_REMAINING_* and VK_WHOLE_SIZE are exported by vulkan_includes.h.
for name, value in (("VK_TRUE", "1U"), ("VK_FALSE", "0U"), ("VK_SHADER_UNUSED_KHR", "(~0U)")):
    out.append(f"export inline constexpr uint32_t {name} = {value};")
out.append("")

out.append("export constexpr uint32_t VK_MAKE_API_VERSION(uint32_t variant, uint32_t major, uint32_t minor, uint32_t patch)")
out.append("{ return (variant << 29U) | (major << 22U) | (minor << 12U) | patch; }")
out.append("export constexpr uint32_t VK_MAKE_VERSION(uint32_t major, uint32_t minor, uint32_t patch)")
out.append("{ return (major << 22U) | (minor << 12U) | patch; }")
for m in re.finditer(r"^#define (VK_API_VERSION_\d_\d)\s+VK_MAKE_API_VERSION\((\d+), (\d+), (\d+), (\d+)\)", core, re.M):
    out.append(f"export inline constexpr uint32_t {m.group(1)} = VK_MAKE_API_VERSION({m.group(2)}, {m.group(3)}, {m.group(4)}, {m.group(5)});")

# The header unit's macros are live in the module interface, so they must go before the same names are declared.
macro_names = []
for l in out:
    m = re.match(r"export (?:inline constexpr (?:const char\*|uint32_t)|constexpr uint32_t) (VK_\w+)", l)
    if m:
        macro_names.append(m.group(1))
out = ["#undef " + n for n in sorted(set(macro_names))] + [""] + out

with open(os.path.join(here, "vulkan_exports.inc"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out) + "\n")
