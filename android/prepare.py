#!/usr/bin/env python3
"""Everything the Android build needs that is not compiling: runs before build.py (F7 does it).

    python android/prepare.py [--mode debug|profile|retail] [--force]

1. vcpkg: installs the arm64-android ports of projects/android/vcpkg.json (generated by
   generate_project.bat) into projects/android/vcpkg_installed. Skipped while the manifest is unchanged.
2. Content: the device has no shader compiler and no image decoders, so spectrum_tool (the Windows build of
   the Tools project, same mode) precompiles every PSO shader, the textures and the engine assets into
   projects/android/shader_cache, which package.py puts in the APK. Skipped while the shaders/PSO
   declarations and the tool are unchanged.
"""
import argparse
import hashlib
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "projects" / "android"
CONTENT = OUT / "shader_cache"
TRIPLET = "arm64-android"

SDK = next((Path(p) for p in (os.environ.get("ANDROID_HOME"), os.environ.get("ANDROID_SDK_ROOT"),
                              os.path.join(os.environ.get("LOCALAPPDATA", ""), "Android", "Sdk"))
            if p and Path(p).is_dir()), None)


def find_ndk():
    if os.environ.get("ANDROID_NDK_HOME") and Path(os.environ["ANDROID_NDK_HOME"]).is_dir():
        return Path(os.environ["ANDROID_NDK_HOME"])
    if SDK and (SDK / "ndk").is_dir():
        return max((d for d in (SDK / "ndk").iterdir() if d.is_dir()),
                   key=lambda d: [int(x) for x in d.name.split(".") if x.isdigit()])
    sys.exit("Android NDK not found (set ANDROID_NDK_HOME)")


def find_vcpkg():
    candidates = []
    if os.environ.get("VCPKG_ROOT"):
        candidates.append(Path(os.environ["VCPKG_ROOT"]) / "vcpkg.exe")
    vswhere = Path(os.environ.get("ProgramFiles(x86)", "")) / "Microsoft Visual Studio" / "Installer" / "vswhere.exe"
    if vswhere.exists():
        r = subprocess.run([str(vswhere), "-latest", "-property", "installationPath"], capture_output=True, text=True)
        if r.stdout.strip():
            candidates.append(Path(r.stdout.strip()) / "VC" / "vcpkg" / "vcpkg.exe")
    for c in candidates:
        if c.exists():
            return c
    sys.exit("vcpkg.exe not found: set VCPKG_ROOT, or install Visual Studio's vcpkg component")


def run_tool(cmd, done_marker, **kw):
    print("  " + " ".join(str(c) for c in cmd), flush=True)
    finished = False
    p = subprocess.Popen([str(c) for c in cmd], stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                         text=True, encoding="utf-8", errors="replace", **kw)
    for line in p.stdout:
        # the engine's per-object leak/stack-trace noise after the work is done is not worth showing
        if line.startswith(("[", "  ", "assets:", "textures:", "shaders:")) or done_marker in line:
            print(line.rstrip(), flush=True)
        if done_marker in line:
            finished = True
    p.wait()
    if p.returncode != 0:
        if not finished:
            sys.exit(f"failed ({p.returncode}) before finishing: {cmd[0]} {cmd[1]}")
        print(f"  warning: {Path(str(cmd[0])).name} exited with {p.returncode} after finishing its work (shutdown crash); continuing")


def digest(paths):
    h = hashlib.sha1()
    for p in paths:
        h.update(p.read_bytes() if p.is_file() else b"")
    return h.hexdigest()


def run(cmd, **kw):
    print("  " + " ".join(str(c) for c in cmd), flush=True)
    r = subprocess.run([str(c) for c in cmd], **kw)
    if r.returncode != 0:
        sys.exit(f"failed ({r.returncode}): {cmd[0]}")


def prepare_vcpkg(force):
    manifest = OUT / "vcpkg.json"
    if not manifest.exists():
        sys.exit(f"{manifest} missing: run generate_project.bat (Sharpmake writes it)")
    stamp = OUT / "vcpkg_installed" / ".spectrum-stamp"
    want = digest([manifest, OUT / "vcpkg-configuration.json"])
    if not force and stamp.exists() and stamp.read_text() == want and (OUT / "vcpkg_installed" / TRIPLET).is_dir():
        print("vcpkg: up to date")
        return
    print("vcpkg: installing the arm64-android ports...")
    env = dict(os.environ, ANDROID_NDK_HOME=str(find_ndk()))
    run([find_vcpkg(), "install", f"--triplet={TRIPLET}", f"--x-manifest-root={OUT}",
         f"--x-install-root={OUT / 'vcpkg_installed'}"], env=env, cwd=ROOT)
    stamp.write_text(want)


def content_inputs():
    """What the precompiled content is derived from: shader sources and the PSO/pass declarations."""
    files = sorted((ROOT / "workdir" / "shaders").rglob("*.hlsl")) + sorted((ROOT / "sources" / "Prism" / "defs").rglob("*.prism"))
    h = hashlib.sha1()
    for p in files:
        st = p.stat()
        h.update(f"{p}|{st.st_mtime_ns}|{st.st_size}\n".encode())
    return h


def prepare_content(mode, force):
    tool = ROOT / "bin" / mode / "spectrum_tool_vulkan.exe"
    if not tool.exists():
        # any other mode's tool produces the same content
        others = [ROOT / "bin" / m / "spectrum_tool_vulkan.exe" for m in ("debug", "profile", "retail")]
        tool = next((t for t in others if t.exists()), tool)
    if not tool.exists():
        sys.exit(f"{tool} missing: build the Tools project (Vulkan) first; F7 on the SpectrumAndroid solution does")
    h = content_inputs()
    h.update(f"{tool.stat().st_mtime_ns}".encode())
    want = h.hexdigest()
    stamp = CONTENT / ".stamp"
    have_blobs = any((CONTENT / "vulkan").glob("*.bin")) and (CONTENT / "assets").is_dir()
    if not force and have_blobs and stamp.exists() and stamp.read_text() == want:
        print("content: up to date")
        return
    print(f"content: precompiling shaders, textures and assets with {tool.name} (takes a while)...")
    CONTENT.mkdir(parents=True, exist_ok=True)
    out = os.path.relpath(CONTENT, ROOT / "workdir")
    # The line each command prints once its output is written. The Debug tool has been seen to crash while
    # shutting down (a worker thread, after the leak report) with everything already saved, so a non-zero
    # exit counts as success only when that line was printed.
    for cmd, done in ((["shaders", "--target", "android"], "output:"), (["textures"], "output:"), (["assets"], "saved, copied")):
        run_tool([tool, *cmd, "--out", out], done, cwd=ROOT / "workdir")
    stamp.write_text(want)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", default="debug", choices=["debug", "profile", "retail"])
    ap.add_argument("--force", action="store_true", help="redo both steps even if they look up to date")
    args = ap.parse_args()
    prepare_vcpkg(args.force)
    prepare_content(args.mode, args.force)
    return 0


if __name__ == "__main__":
    sys.exit(main())
